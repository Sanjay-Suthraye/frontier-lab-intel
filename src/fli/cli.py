@app.command()
def costs() -> None:
    """LLM and metered-API spend by workflow and model (from the llm_call / api_usage ledgers)."""
    from sqlalchemy import func, select

    from fli.db.models import ApiUsage, LLMCall
    from fli.db.session import session_scope

    with session_scope() as s:
        rows = s.execute(
            select(LLMCall.purpose, LLMCall.model, func.count(), func.sum(LLMCall.input_tokens),
                   func.sum(LLMCall.output_tokens), func.sum(LLMCall.cache_read_tokens),
                   func.sum(LLMCall.cache_write_tokens), func.sum(LLMCall.cost_usd))
            .group_by(LLMCall.purpose, LLMCall.model).order_by(func.sum(LLMCall.cost_usd).desc())
        ).all()
        api = s.execute(select(ApiUsage.provider, func.sum(ApiUsage.units), func.sum(ApiUsage.cost_usd))
                        .group_by(ApiUsage.provider)).all()
    _print({
        "llm": [{"purpose": p, "model": m, "calls": c, "input_tokens": i or 0, "output_tokens": o or 0,
                 "cache_read_tokens": cr or 0, "cache_write_tokens": cw or 0, "usd": round(u or 0.0, 4)}
                for p, m, c, i, o, cr, cw, u in rows],
        "llm_total_usd": round(sum((r[7] or 0.0) for r in rows), 4),
        "metered_apis": [{"provider": p, "units": u or 0, "usd": round(c or 0.0, 4)} for p, u, c in api],
    })


@app.command()
def serve(host: str = "127.0.0.1", port: int = 8000, reload: bool = False) -> None:
    """Run the web UI + JSON API."""
    import uvicorn

