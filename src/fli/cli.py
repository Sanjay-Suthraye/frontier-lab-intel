"""`fli` command line. Each command is a thin wrapper around a module function so that the
scheduler, tests and the CLI all exercise the same code path."""

from __future__ import annotations

import json
from datetime import datetime

import typer

from fli.logs import setup_logging

app = typer.Typer(help="Frontier Lab Intelligence", no_args_is_help=True, add_completion=False)
db_app = typer.Typer(help="Database utilities", no_args_is_help=True)
app.add_typer(db_app, name="db")


def _print(obj) -> None:
    typer.echo(json.dumps(obj, indent=2, default=str))


def _call(target: str, /, **kwargs):
    """Resolve 'module:function' lazily (positional-only so commands may pass a `path=` kwarg)."""
    from fli.pipeline import resolve

    try:
        fn = resolve(target)
    except (ModuleNotFoundError, AttributeError) as exc:
        typer.secho(f"{target} is not available: {exc}", fg=typer.colors.RED)
        raise typer.Exit(2) from exc
    return fn(**kwargs)


@app.callback()
def main(verbose: bool = typer.Option(False, "--verbose", "-v")) -> None:
    setup_logging("DEBUG" if verbose else None)


# ------------------------------------------------------------------------------------ database
@db_app.command("init")
def db_init() -> None:
    """Create all tables (idempotent)."""
    from fli.db.session import init_db

    init_db()
    typer.echo("database initialised")


@db_app.command("schema")
def db_schema(out: str = typer.Option("docs/schema.sql", help="where to write the Postgres DDL")) -> None:
    """Write the Postgres DDL for the full schema (the schema deliverable)."""
    from sqlalchemy.dialects import postgresql
    from sqlalchemy.schema import CreateIndex, CreateTable

    from fli.db.models import Base

    dialect = postgresql.dialect()
    parts = []
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for idx in sorted(table.indexes, key=lambda i: i.name or ""):
            parts.append(str(CreateIndex(idx).compile(dialect=dialect)).strip() + ";")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("-- Generated by `fli db schema` from src/fli/db/models.py\n\n" + "\n\n".join(parts) + "\n")
    typer.echo(f"wrote {out}")


